for (const [id, [meta, say]] of Object.entries(TALK)) {
  const f = `${D}/${id}.html`;
  const h = fs.readFileSync(f, 'utf8');
  const m = h.match(/<aside>([\s\S]*?)<\/aside>/);
  if (!m) throw new Error('no aside in ' + id);
  const body = m[1].trim().replace(/^\[[^\]]+\]\s*/, '');
  const keep = body.split(/\n\s*\n/).map((p) => p.trim()).filter((p) => /^(ถ้าถูกถาม|ห้ามพูด)/.test(p));
  const aside = `<aside>[${meta}] ${[...say, ...keep].join('\n\n')}</aside>`;
  if (aside.length > 4000) throw new Error(`${id} notes ${aside.length} chars, over 4000`);
  fs.writeFileSync(f, h.replace(m[0], aside));
}
