const LEVELS = [0, 10, 20, 40, 80];

function makeArm(n) {
  const lines = [
    '# แนวปฏิบัติสำหรับผู้ช่วยเขียนโค้ดในโปรเจกต์นี้',
    '',
    `> Arm การทดลอง Rule Dilution — มีกฎประกอบ ${n} ข้อ`,
    '> กฎเป้าหมายอยู่ท้ายไฟล์และเหมือนกันทุก arm',
    '',
  ];
  if (n > 0) {
    lines.push('## แนวปฏิบัติทั่วไปของทีม', '');
    for (let i = 0; i < n; i++) lines.push(`${i + 1}. ${FILLER[i % FILLER.length]}`);
    lines.push('');
  }
  lines.push(TARGET_RULE, '');
  return lines.join('\n');
}

fs.rmSync(OUT, { recursive: true, force: true });
const arms = [];

for (const n of LEVELS) {
  const id = `D${String(n).padStart(3, '0')}`;
  const dir = path.join(OUT, id);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'CLAUDE.md'), makeArm(n), 'utf8');
  arms.push({
    id,
    name: `Dilution +${n} rules`,
    role: n === 0 ? 'reference' : 'dilution',
    desc: `กฎเป้าหมาย 1 ข้อ + กฎประกอบที่ไม่เกี่ยวข้อง ${n} ข้อ`,
    contextFiles: [`arms/dilution/${id}/CLAUDE.md`],
    skillsEnabled: false,
    ruleCount: n + 1,
  });
}

const config = {
  _note: 'การทดลอง Rule Dilution — ตัวแปรเดียวที่ต่างคือจำนวนกฎที่โหลดพร้อมกัน',
  _readAs: 'ถ้าอัตราการทำตามกฎเป้าหมายลดลงตามจำนวนกฎที่เพิ่ม แสดงว่ากฎเจือจางกันเอง',
  arms,
  fixedFactors: {
    model: 'claude-opus-5',
    temperature: 1.0,
    maxTurns: 25,
    _note: 'ใช้เฉพาะ scenario ตระกูล hidden_impact เพราะกฎเป้าหมายเกี่ยวกับผลกระทบย้อนหลัง',
  },
  primaryEndpoint: {
    metric: 'IM (กลุ่มกฎผลกระทบย้อนหลัง)',
    comparison: 'D000 vs D080',
  },
};

fs.writeFileSync(path.join(ROOT, 'config/dilution.json'), JSON.stringify(config, null, 2) + '\n', 'utf8');

console.log('\nสร้าง arm สำหรับ Rule Dilution แล้ว\n');
for (const a of arms) {
  const chars = fs.readFileSync(path.join(ROOT, a.contextFiles[0]), 'utf8').length;
  console.log(`  ${a.id}  กฎ ${String(a.ruleCount).padStart(2)} ข้อ  ${String(chars).padStart(5)} อักขระ`);
}
